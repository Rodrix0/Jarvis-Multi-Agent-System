const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { DesktopCompanionService } = require('../services/desktopCompanionService');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'jarvis-companion-test-'));
let now = 10000, launches = 0;
const settingsPath = path.join(temp, 'preferences.json');
const service = new DesktopCompanionService({ now: () => now, settingsPath, platform: 'win32', launch: (exe, args, options) => {
    launches++; assert.equal(options.windowsHide, true); assert.ok(args.includes('-STA'));
    const child = new EventEmitter(); child.stderr = new EventEmitter(); child.kill = () => {};
    return child;
} });
assert.equal(service.snapshot().visible, false);
service.presence('a', { visible: true }); service.presence('b', { visible: false });
assert.equal(launches, 1, 'one native instance for multiple browser tabs');
assert.equal(service.snapshot().visible, false, 'visible interface hides character');
service.presence('a', { visible: false });
assert.equal(service.snapshot().visible, true, 'minimized interface reveals character');
service.observe('action_status', { phase: 'accepted', message: 'Preparando documento' });
assert.equal(service.snapshot().state, 'working');
service.observe('action_status', { phase: 'completed', message: 'Terminé' });
assert.equal(service.snapshot().state, 'working', 'wait for the actual final response');
service.observe('response', { status: 'completed', text: 'Documento listo' });
assert.equal(service.snapshot().state, 'completed');
const revision = service.snapshot().revision;
service.observe('response', { status: 'completed', text: 'Documento listo' });
assert.equal(service.snapshot().revision, revision, 'broadcast fanout does not duplicate notifications');
service.observe('response', { status: 'failed', text: 'No pude crear el archivo' });
assert.equal(service.snapshot().state, 'failed');
service.observe('response', { confirmationToken: 'test', text: 'Confirmá en Jarvis' });
assert.equal(service.snapshot().state, 'waiting');
service.observe('response', {status:'completed',text:'¿En qué carpeta querés guardarlo?'});
assert.equal(service.snapshot().state,'waiting','a clarification question stays pending even if the conversational route returns completed');
service.observe('response', { status: 'working', text: 'Sigo trabajando' });
assert.equal(service.snapshot().state, 'working');
service.observe('notification', { title: 'Recordatorio', message: 'Reunión' });
assert.equal(service.snapshot().title, 'Recordatorio');
service.observe('response', { text: '<b>Respuesta</b> ' + 'x'.repeat(1000) });
assert.equal(service.snapshot().text.includes('<b>'), false);
assert.ok(service.snapshot().text.length <= 420);
service.detach('a'); service.detach('b');
assert.equal(service.snapshot().visible, true, 'closing the UI does not lose the companion');
service.configure(false);
assert.equal(service.snapshot().visible, false);
assert.equal(new DesktopCompanionService({ settingsPath, platform: 'test' }).enabled, false, 'disabled setting survives restarts');
service.configure(true); service.presence('c', { visible: true }); service.previewUntil = now + 12000;
assert.equal(service.snapshot().visible, true);
now += 12001; assert.equal(service.snapshot().visible, false, 'preview expires');
const routes = {}; const app = { get(route, fn) { routes[route] = fn; } }; const io = new EventEmitter();
service.configure(true,false);
assert.equal(new DesktopCompanionService({settingsPath,platform:'test'}).animations,false,'motion preference survives restart');
service.configure(true,true);
service.install(app, io, 12345);
const speech=require('../services/bargeInService');const speechId=speech.notifySpeechStarted('Prueba');
assert.equal(service.snapshot().speaking,true);speech.notifySpeechEnded(speechId);assert.equal(service.snapshot().speaking,false);
io.emit('response', { status: 'completed', text: 'Funciona sin una pestaña abierta' });
assert.equal(service.snapshot().text, 'Funciona sin una pestaña abierta');
let status, body;
const res = { sendStatus(code) { status = code; }, set() { return this; }, json(value) { body = value; } };
routes['/api/companion/state']({ socket: { remoteAddress: '127.0.0.1' }, get: () => 'invalid' }, res);
assert.equal(status, 403);
routes['/api/companion/state']({ socket: { remoteAddress: '127.0.0.1' }, get: () => service.token }, res);
assert.equal(body.state, 'completed');
console.log('PASS: native singleton, visibility across tabs, progress/results/failure/confirmation, reminders, persistence and local token protection.');
